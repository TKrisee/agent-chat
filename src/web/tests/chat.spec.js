import { test, expect } from './fixture.js';
import { randomUUID } from 'node:crypto';

test('drop and send an attachment; preserve it for retry after a failed send', async ({ page, serviceURL }) => {
  await page.goto(serviceURL);
  const header = page.locator('.channel-header');
  await expect(header.getByRole('heading', { name: 'Root' })).toBeVisible();
  await expect.poll(async () => (await header.boundingBox())?.height ?? Infinity).toBeLessThanOrEqual(56);
  const composer = page.getByLabel('Message Root');
  const add = page.getByRole('button', { name: 'Add attachment' });
  const upload = page.getByRole('button', { name: 'Upload a file' });
  await expect(page.getByRole('button', { name: 'Send message' })).toHaveCount(0);
  await expect(page.locator('.compose-bottom')).toHaveCount(0);
  await expect(composer).toBeVisible();
  let inputBox;
  await expect.poll(async () => {
    const box = await composer.boundingBox();
    if (box) inputBox = box;
    return box?.height ?? 0;
  }).toBeGreaterThan(0);
  const initialHeight = inputBox.height;
  await add.click();
  await expect(upload).toBeVisible();
  await expect.poll(async () => (await upload.boundingBox())?.y ?? Infinity).toBeLessThan(inputBox.y);
  await page.keyboard.press('Escape');
  await expect(upload).toBeHidden();
  await expect(add).toBeFocused();
  await add.click();
  await composer.click();
  await expect(upload).toBeHidden();
  await composer.fill('First line');
  await composer.press('Shift+Enter');
  await expect(composer).toHaveValue('First line\n');
  await expect.poll(async () => ((await composer.boundingBox())?.height ?? -1)).toBeGreaterThan(initialHeight);
  await page.getByRole('link', { name: /Root conversation/ }).click();
  await expect(composer).toHaveValue('First line\n');
  await expect.poll(async () => ((await composer.boundingBox())?.height ?? -1)).toBeGreaterThan(initialHeight);
  await composer.fill(Array(50).fill('Long draft').join('\n'));
  await expect.poll(async () => ((await composer.boundingBox())?.height ?? Infinity)).toBeLessThanOrEqual(240);
  await expect.poll(() => composer.evaluateAll(els => els.some(el => el.scrollHeight > el.clientHeight))).toBe(true);
  await expect.poll(async () => {
    const input = await composer.boundingBox();
    const button = await add.boundingBox();
    return input && button ? Math.abs(input.y - button.y) : Infinity;
  }).toBeLessThan(4);
  await composer.fill('');
  await expect.poll(async () => ((await composer.boundingBox())?.height ?? -1)).toBe(initialHeight);
  await composer.fill(Array(40).fill('Earlier conversation').join('\n\n'));
  await composer.press('Enter');
  await expect(page.getByRole('article').filter({hasText:'Earlier conversation'}).first()).toBeVisible();
  const scroll = page.locator('#chat-scroll');
  await expect.poll(() => scroll.evaluate(el => el.scrollHeight-el.clientHeight)).toBeGreaterThan(300);
  // The first message can render before its send acknowledgement and final scroll.
  await expect(page.locator('#composer')).toHaveAttribute('aria-busy', 'false');
  await expect.poll(() => scroll.evaluate(el => el.scrollHeight-el.clientHeight-el.scrollTop)).toBeLessThan(3);
  await scroll.evaluate(el => {el.scrollTop=0;});
  await expect.poll(() => scroll.evaluate(el => el.scrollTop)).toBe(0);
  const transfer = await page.evaluateHandle(() => {
    const data = new DataTransfer();
    const png = Uint8Array.from(atob('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+/a9sAAAAASUVORK5CYII='), c => c.charCodeAt(0));
    data.items.add(new File([png], 'tiny.png', { type: 'image/png' }));
    return data;
  });
  await page.locator('.chat').dispatchEvent('drop', { dataTransfer: transfer });
  await expect(page.getByLabel('Attachments').getByText('tiny.png')).toBeVisible();
  const thumbnail = page.getByRole('img', { name: 'Preview of tiny.png' });
  await expect(thumbnail).toBeVisible();
  await expect.poll(() => thumbnail.evaluate(image => image.naturalWidth)).toBeGreaterThan(0);
  await composer.fill('Please review the notes');
  await composer.press('Enter');
  await expect(page.getByRole('article').filter({ hasText: 'Please review the notes' }).getByText('tiny.png')).toBeVisible();
  await expect.poll(() => scroll.evaluate(el => el.scrollHeight-el.clientHeight-el.scrollTop)).toBeLessThan(3);
  await expect.poll(async () => ((await composer.boundingBox())?.height ?? -1)).toBe(initialHeight);

  await add.click();
  const refreshWithMessage = async text => {
    const response = await page.request.post(`${serviceURL}/api/messages/upload`, {multipart:{id:randomUUID(),recipient:'root',text}});
    expect(response.status()).toBe(201);
    await expect(page.getByRole('article').filter({hasText:text}).first()).toBeVisible({timeout:15000});
  };
  await refreshWithMessage('Background update with attachment menu open');
  await expect(upload).toBeVisible();
  await expect(upload).toBeFocused();
  const chooser = page.waitForEvent('filechooser');
  await upload.click();
  const selected = await chooser;
  await refreshWithMessage('Background update with file chooser open');
  await selected.setFiles({ name: 'retry.txt', mimeType: 'text/plain', buffer: Buffer.from('retry') });
  await expect(upload).toBeHidden();
  await composer.fill('Retry this upload');
  let releaseUpload;
  let uploadStarted;
  const started = new Promise(resolve => { uploadStarted = resolve; });
  await page.route('**/api/messages/upload', async route => {
    uploadStarted();
    await new Promise(resolve => { releaseUpload = resolve; });
    await route.abort();
  });
  const beforeSend = await composer.boundingBox();
  await composer.press('Enter');
  await started;
  await expect(page.locator('#composer')).toHaveAttribute('aria-busy', 'true');
  await expect(page.locator('.pending, #check-delivery')).toHaveCount(0);
  const duringSend = await composer.boundingBox();
  expect(Math.abs(duringSend.y - beforeSend.y)).toBeLessThan(2);
  expect(Math.abs(duringSend.height - beforeSend.height)).toBeLessThan(2);
  await expect(composer).toBeFocused();
  await expect(page.getByLabel('Attachments').getByText('retry.txt')).toBeVisible();
  releaseUpload();
  await expect(page.locator('#composer')).toHaveAttribute('aria-busy', 'false');
  await page.unroute('**/api/messages/upload');
  const pendingId = await page.evaluate(() => sessionStorage.getItem('pending-id:root'));
  expect(pendingId).toBeTruthy();
  await page.reload();
  await expect(composer).toHaveValue('Retry this upload');
  await expect(add).toBeEnabled();
  await composer.press('Enter');
  await expect(add).toBeFocused();
  await expect(page.locator('#composer .sr-only[role=status]')).toContainText('Reattach the files');
  await add.click();
  const reattach = page.waitForEvent('filechooser');
  await upload.click();
  await (await reattach).setFiles({ name: 'retry.txt', mimeType: 'text/plain', buffer: Buffer.from('retry') });
  expect(await page.evaluate(() => sessionStorage.getItem('pending-id:root'))).toBe(pendingId);
  await composer.press('Enter');
  await expect(page.getByRole('article').filter({ hasText: 'Retry this upload' }).getByText('retry.txt')).toBeVisible();
});

test('image gallery stays within one message and downloads the selected image', async ({page, serviceURL}) => {
  const state = `{"projects":[],"agents":[{"id":"root","name":"Root","role":"root","project_id":"","status":"idle","model":"test"}],"tasks":[],"jobs":[],"messages":[{"id":"gallery-message","room_id":"dm:operator:root","sender":"root","recipient":"operator","role":"root","text":"Gallery","at":"2026-01-01T00:00:00Z","attachments":[{"id":"image-one","name":"one.png","media_type":"image/png"},{"id":"image-two","name":"two.png","media_type":"image/png"},{"id":"image-three","name":"three.png","media_type":"image/png"},{"id":"notes","name":"notes.txt","media_type":"text/plain"}]},{"id":"other-message","room_id":"dm:operator:root","sender":"root","recipient":"operator","role":"root","text":"Other","at":"2026-01-01T00:00:01Z","attachments":[{"id":"other-image","name":"other.png","media_type":"image/png"}]}]}`;
  await page.route('**/api/state', route => route.fulfill({status:200,contentType:'application/json',body:state}));
  await page.route('**/api/attachments/*/preview', route => route.fulfill({status:200,contentType:'image/png',body:Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mNk+A8AAQUBAScY42YAAAAASUVORK5CYII=', 'base64')}));
  await page.goto(serviceURL);
  const gallery = page.locator('[data-message-id="gallery-message"]');
  await expect(gallery.locator('.attachment-image-grid [data-attachment-preview]')).toHaveCount(3);
  await expect(gallery.locator('.attachment-image-grid [data-attachment-preview="notes"]')).toHaveCount(0);
  await expect(gallery.getByRole('button',{name:'Preview notes.txt'})).toBeVisible();
  await expect(page.locator('[data-message-id="other-message"] .attachment-image-grid')).toHaveCount(0);
  await page.locator('[data-attachment-preview="image-two"]').click();
  const dialog=page.locator('dialog.attachment-preview');
  await expect(dialog).toBeVisible();
  await expect(dialog.getByRole('heading',{name:'two.png'})).toBeVisible();
  await expect(dialog.getByRole('link',{name:'Download'})).toHaveAttribute('href','/api/attachments/image-two?download=1');
  await expect(dialog.getByRole('button',{name:'Show two.png'})).toHaveAttribute('aria-pressed','true');
  await expect(dialog.getByRole('button',{name:'Show other.png'})).toHaveCount(0);
  await dialog.getByRole('button',{name:'Next image'}).click();
  await expect(dialog.getByRole('heading',{name:'three.png'})).toBeVisible();
  await expect(dialog.getByRole('link',{name:'Download'})).toHaveAttribute('href','/api/attachments/image-three?download=1');
  await dialog.press('ArrowLeft');
  await expect(dialog.getByRole('heading',{name:'two.png'})).toBeVisible();
  await dialog.getByRole('button',{name:'Show one.png'}).click();
  await expect(dialog.getByRole('heading',{name:'one.png'})).toBeVisible();
  await dialog.getByRole('button',{name:'Next image'}).click();
  await dialog.getByRole('button',{name:'Previous image'}).click();
  await expect(dialog.getByRole('heading',{name:'one.png'})).toBeVisible();
  await dialog.press('Escape');
  await expect(dialog).toBeHidden();
  await expect(page.locator('[data-attachment-preview="image-two"]')).toBeFocused();
});
