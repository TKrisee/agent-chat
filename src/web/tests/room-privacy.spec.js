import { test, expect } from './fixture.js';

test('group and agent conversations stay in their own rooms', async ({ page, serviceURL }) => {
  await page.goto(serviceURL);
  const root = page.getByLabel('Message Root');
  await root.fill('Start project atlas: Check room visibility');
  await root.press('Enter');
  const project = page.locator('[data-project="atlas"]');
  await expect(project).toBeVisible({timeout: 20000});
  await project.click();
  const group = page.getByLabel('Message atlas chat');
  const scopeNotice = page.getByRole('article', {name:'Agent Chat workflow notice'}).filter({hasText:'Root sent the project owner a request for scope assessment.'});
  const scopeButton = scopeNotice.getByRole('button', {name:'View scope request'});
  await expect(scopeButton).toBeVisible({timeout:20000});
  await scopeButton.click();
  await expect(scopeNotice.locator('.scope-detail')).toContainText('Check room visibility');
  await scopeNotice.getByRole('button', {name:'Hide scope request'}).click();
  await expect(scopeNotice.locator('.scope-detail')).toBeHidden();

  const dispatchNotice = page.getByRole('article', {name:'Agent Chat workflow notice'}).filter({hasText:'The project owner queued work for a worker.'});
  await expect(dispatchNotice).toBeVisible({timeout:20000});
  await expect(dispatchNotice.locator('[data-reply]')).toHaveCount(0);
  await expect(dispatchNotice.getByRole('button', {name:'View scope request'})).toHaveCount(0);
  await expect(page.locator('.composer-heading')).not.toContainText('Idle');
  await expect(page.locator('[data-agent]').first()).toHaveAttribute('aria-label', /(?:Idle|Working|Starting|Queued|Needs attention|Failed|Stopped|Status unavailable)/);
  await group.fill('Shared untagged message');
  await group.press('Enter');
  await expect(page.locator('.chat').getByText('Shared untagged message', {exact:true})).toBeVisible();
  const lead = page.locator('[data-agent]').first();
  await expect(lead).toBeVisible();
  const leadId = await lead.getAttribute('data-agent');
  await expect(page.getByRole('button', {name:'@ Mention'})).toHaveCount(0);
  await group.pressSequentially('@');
  await group.press('ArrowDown');
  const choice = page.locator(`[data-mention-choice="${leadId}"]`);
  await expect(choice).toBeFocused();
  await choice.press('Enter');
  await group.press('End');
  await group.pressSequentially(' Shared tagged message');
  await group.press('Enter');
  const taggedPost = page.locator('.chat article.message').filter({has:page.locator('.message-meta strong').getByText('operator', {exact:true})}).filter({hasText:'Shared tagged message'});
  await expect(taggedPost).toHaveCount(1);
  await expect(taggedPost).toBeVisible();
  await expect(page.locator('.chat').getByText('PO replied in the project group:', {exact:false})).toBeVisible({timeout:20000});
  await expect(page.locator('#composer')).toHaveAttribute('aria-busy','false');
  await lead.click();
  const direct = page.locator('#message');
  await expect(dispatchNotice).toHaveCount(0);
  await expect(page.getByRole('button', {name:'View scope request'})).toHaveCount(0);
  await expect(page.locator('.chat').getByText('Shared untagged message', {exact:true})).toHaveCount(0);
  await expect(page.getByText('Shared tagged message', {exact:false})).toHaveCount(0);
  await expect(page.getByText('PO replied in the project group:', {exact:false})).toHaveCount(0);
  let releaseDirect;
  let directCommitted, directFinished;
  const directReady = new Promise(resolve => { directCommitted = resolve; });
  const directDone = new Promise(resolve => { directFinished = resolve; });
  await page.route('**/api/messages/upload', async route => {
    const response = await route.fetch();
    directCommitted();
    await new Promise(resolve => { releaseDirect = resolve; });
    try { await route.fulfill({response}); } finally { directFinished(); }
  });
  await direct.fill('Private direct message');
  await direct.press('Enter');
  await directReady;
  await project.click();
  await expect(page.locator('.chat').getByText('Shared untagged message', {exact:true})).toBeVisible();
  await expect(page.getByText('Private direct message', {exact:true})).toHaveCount(0);
  await page.getByRole('button', {name:/Root conversation/}).click();
  const rootComposer=page.getByLabel('Message Root');
  await rootComposer.fill('/stop missing');
  await rootComposer.press('Enter');
  await expect(page.getByText('Project missing was not found.', {exact:false})).toBeVisible();
  await expect(rootComposer).toHaveValue('/stop missing');
  await rootComposer.fill('/stop atlas');
  let releaseStop, stopStarted, stopFinished, stopCount=0;
  const stopReady=new Promise(resolve=>{stopStarted=resolve;});
  const stopDone=new Promise(resolve=>{stopFinished=resolve;});
  await page.route('**/api/projects/atlas/stop', async route=>{
    stopCount++;
    const response=await route.fetch();
    stopStarted();
    await new Promise(resolve=>{releaseStop=resolve;});
    try { await route.fulfill({response}); } finally { stopFinished(); }
  });
  const stopResponse=page.waitForResponse(r=>r.url().endsWith('/api/projects/atlas/stop') && r.request().method()==='POST');
  await rootComposer.press('Enter');
  await stopReady;
  await rootComposer.press('Enter');
  expect(stopCount).toBe(1);
  releaseStop();
  expect((await stopResponse).status()).toBe(200);
  await stopDone;
  await page.unroute('**/api/projects/atlas/stop');
  await expect(page.getByText(/Stop requested for atlas\. \d+ jobs? remain(?:s)? submitted, running or uncertain\./)).toBeVisible();
  await expect(project.locator('small')).toHaveText(/^(stopped|stopping)$/);
  await expect(rootComposer).toHaveValue('');
  releaseDirect();
  await directDone;
  await page.unroute('**/api/messages/upload');
  await project.click();
  await lead.click();
  await expect(page.locator('.chat').getByText('Private direct message', {exact:true})).toBeVisible();
});

test('project panel shows current work once and preserves earlier uncertainty', async ({page, serviceURL}) => {
  // Fixed state models an older uncertain attempt and a newer submitted attempt.
  const state = `{"projects":[{"id":"sample","name":"Sample","status":"running","po_id":"11111111-1111-4111-8111-111111111111","goal_objective":"Deliver the full goal","goal_status":"active"}],"agents":[{"id":"root","name":"Root","role":"root","project_id":"","status":"idle","model":"test"},{"id":"11111111-1111-4111-8111-111111111111","name":"Sample-PO","role":"po","project_id":"sample","status":"busy","model":"test"}],"tasks":[{"id":"22222222-2222-4222-8222-222222222222","project_id":"sample","title":"Deliver launch","status":"blocked","owner_id":"11111111-1111-4111-8111-111111111111","continue_po_eligible":true},{"id":"55555555-5555-4555-8555-555555555555","project_id":"sample","title":"Finalize handoff","status":"blocked","owner_id":"11111111-1111-4111-8111-111111111111","retry_handoff_eligible":true}],"jobs":[{"id":"33333333-3333-4333-8333-333333333333","agent_id":"11111111-1111-4111-8111-111111111111","project_id":"sample","task_id":"22222222-2222-4222-8222-222222222222","status":"uncertain","diagnostic":"Earlier run outcome unknown"},{"id":"44444444-4444-4444-8444-444444444444","agent_id":"11111111-1111-4111-8111-111111111111","project_id":"sample","task_id":"22222222-2222-4222-8222-222222222222","status":"submitted"}],"messages":[]}`;
  await page.route('**/api/state', route=>route.fulfill({status:200,contentType:'application/json',body:state}));
  let releaseRetry;
  const heldRetry=new Promise(resolve=>{releaseRetry=resolve;});
  let retries=0;
  await page.route('**/api/tasks/55555555-5555-4555-8555-555555555555/retry-handoff', async route=>{retries++;await heldRetry;await route.fulfill({status:202,body:'Handoff correction queued.'});});
  let releasePO;
  const heldPO=new Promise(resolve=>{releasePO=resolve;});
  let continuations=0, submittedNote='';
  await page.route('**/api/tasks/22222222-2222-4222-8222-222222222222/continue-po', async route=>{continuations++;submittedNote=route.request().postData()||'';await heldPO;await route.fulfill({status:202,body:'PO continuation queued.'});});
  await page.goto(serviceURL);
  await page.locator('[data-project="sample"]').click();
  const panel=page.getByLabel('Sample activity');
  await expect(panel.getByRole('heading',{name:'Team'})).toBeVisible();
  await expect(panel.locator('.pa-team li').filter({hasText:'Sample-PO'})).toContainText('Starting');
  await expect(page.getByText('PROJECT LEAD',{exact:true})).toHaveCount(0);
  await expect(page.getByText('Recent work',{exact:true})).toHaveCount(0);
  await panel.getByText('PO goal',{exact:false}).click();
  await expect(panel.getByText('Deliver the full goal')).toBeVisible();
  await panel.getByText('Work',{exact:false}).click();
  await expect(panel.getByText('Deliver launch',{exact:true})).toHaveCount(1);
  await expect(panel.locator('.pa-work li').filter({hasText:'Deliver launch'})).toContainText('Starting');
  await panel.getByText('Details',{exact:true}).click();
  await expect(panel.getByText('Earlier run outcome unknown')).toBeVisible();
  await expect(panel.getByRole('button',{name:'Retry handoff'})).toHaveCount(0);
  await expect(panel.getByRole('button',{name:'Continue with PO'})).toHaveCount(0);
  const composer=page.getByLabel('Message Sample chat');
  await composer.fill('/cont');
  await expect(page.getByRole('listbox',{name:'Slash commands'}).getByRole('option')).toHaveCount(1);
  await composer.press('Enter');
  await expect(composer).toHaveValue('/continue ');
  await composer.fill('/continue Review the existing evidence');
  await composer.press('Enter');
  await expect.poll(()=>continuations).toBe(1);
  const submitted=new URLSearchParams(submittedNote);
  expect(submitted.get('id')).toMatch(/^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/);
  expect(submitted.get('note')).toBe('Review the existing evidence');
  releasePO();
  await expect(page.getByRole('status').filter({hasText:'PO continuation queued.'})).toBeVisible();
  await composer.fill('/retry-handoff ');
  await composer.press('Enter');
  await expect.poll(()=>retries).toBe(1);
  releaseRetry();
  await expect(page.getByRole('status').filter({hasText:'Handoff correction queued'})).toBeVisible();
});
